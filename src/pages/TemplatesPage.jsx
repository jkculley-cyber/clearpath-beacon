const TEAL = [42, 157, 143];
const NAVY = [26, 35, 50];
const GRAY = [100, 100, 100];
const BLACK = [30, 30, 30];
const MARGIN = 18;
const PAGE_W = 215.9; // letter mm
const PAGE_H = 279.4;
const CONTENT_W = PAGE_W - MARGIN * 2;

function today() {
  return new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
}

function shortDate() {
  return new Date().toLocaleDateString('en-US', { month: '2-digit', day: '2-digit', year: 'numeric' });
}

/** Draw the standard Beacon header bar + title */
function drawHeader(doc, title, subtitle) {
  doc.setFillColor(...TEAL);
  doc.rect(0, 0, PAGE_W, 32, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text('Beacon', MARGIN, 15);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text('Clear Path Education Group, LLC', MARGIN, 25);

  doc.setTextColor(...NAVY);
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text(title, MARGIN, 46);

  if (subtitle) {
    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(...GRAY);
    doc.text(subtitle, MARGIN, 54);
  }
}

/** Add footer to every page */
function drawFooter(doc) {
  const pageCount = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(160, 160, 160);
    doc.text('Generated by Beacon | clearpathedgroup.com', MARGIN, PAGE_H - 8);
    if (pageCount > 1) {
      doc.text(`Page ${i} of ${pageCount}`, PAGE_W - MARGIN, PAGE_H - 8, { align: 'right' });
    }
  }
}

/** Draw a labeled field with an underline */
function drawField(doc, label, x, y, lineW) {
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...NAVY);
  doc.text(label, x, y);
  doc.setDrawColor(180, 180, 180);
  doc.setLineWidth(0.3);
  doc.line(x, y + 2, x + lineW, y + 2);
  return y + 10;
}

/** Draw pre-filled label: value */
function drawInfo(doc, label, value, x, y) {
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...NAVY);
  const labelText = `${label}: `;
  doc.text(labelText, x, y);
  const labelW = doc.getTextWidth(labelText);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...BLACK);
  doc.text(value || '', x + labelW, y);
  return y + 7;
}

/** Draw a section heading */
function drawSection(doc, text, y) {
  doc.setFillColor(240, 245, 245);
  doc.rect(MARGIN, y - 4, CONTENT_W, 8, 'F');
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...TEAL);
  doc.text(text, MARGIN + 3, y + 1.5);
  return y + 12;
}

/** Draw lined area */
function drawLines(doc, y, count, x, w) {
  x = x || MARGIN;
  w = w || CONTENT_W;
  doc.setDrawColor(200, 200, 200);
  doc.setLineWidth(0.2);
  for (let i = 0; i < count; i++) {
    const ly = y + i * 7;
    doc.line(x, ly, x + w, ly);
  }
  return y + count * 7 + 3;
}

/** Draw checkbox options */
function drawCheckboxes(doc, options, x, y, cols) {
  cols = cols || 2;
  const colW = CONTENT_W / cols;
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...BLACK);
  options.forEach((opt, i) => {
    const col = i % cols;
    const row = Math.floor(i / cols);
    const cx = x + col * colW;
    const cy = y + row * 7;
    doc.setDrawColor(120, 120, 120);
    doc.setLineWidth(0.3);
    doc.rect(cx, cy - 3, 3.5, 3.5);
    doc.text(opt, cx + 5.5, cy);
  });
  const rows = Math.ceil(options.length / cols);
  return y + rows * 7 + 3;
}

/** Signature block */
function drawSignature(doc, label, y) {
  doc.setDrawColor(120, 120, 120);
  doc.setLineWidth(0.3);
  doc.line(MARGIN, y, MARGIN + 80, y);
  doc.line(MARGIN + 90, y, MARGIN + 130, y);
  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...GRAY);
  doc.text(label, MARGIN, y + 5);
  doc.text('Date', MARGIN + 90, y + 5);
  return y + 14;
}

/** Dual signature block */
function drawDualSignature(doc, label1, label2, y) {
  const halfW = CONTENT_W / 2 - 5;
  doc.setDrawColor(120, 120, 120);
  doc.setLineWidth(0.3);
  // Left
  doc.line(MARGIN, y, MARGIN + halfW, y);
  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...GRAY);
  doc.text(label1, MARGIN, y + 5);
  // Right
  const rx = MARGIN + halfW + 10;
  doc.line(rx, y, rx + halfW, y);
  doc.text(label2, rx, y + 5);
  return y + 14;
}

/** Check if we need a new page */
function checkPage(doc, y, needed) {
  if (y + needed > PAGE_H - 20) {
    doc.addPage();
    return 20;
  }
  return y;
}

