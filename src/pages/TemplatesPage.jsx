function generateReferralAck(counselor, student) {
  const doc = new jsPDF({ format: 'letter' });
  const sName = student?.name || '________________________';
  drawHeader(doc, 'Referral Acknowledgment Letter');

  let y = 62;
  y = drawInfo(doc, 'Student', sName, MARGIN, y);
  y = drawInfo(doc, 'Date', today(), MARGIN, y);
  y = drawInfo(doc, 'Counselor', counselor?.name || '', MARGIN, y);
  y = drawInfo(doc, 'Campus', counselor?.campus || '', MARGIN, y);
  y += 5;

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...BLACK);
  doc.text('Dear Parent/Guardian,', MARGIN, y);
  y += 8;
  const intro = doc.splitTextToSize(
    `We have received a referral for your child, ${student?.name || '[Student Name]'}, for school counseling services. ` +
    'This letter is to inform you of the referral and the next steps we will take to support your child.',
    CONTENT_W
  );
  doc.text(intro, MARGIN, y);
  y += intro.length * 5 + 8;

  y = drawSection(doc, 'Referral Details', y);
  y = drawField(doc, 'Referral Source:', MARGIN, y, CONTENT_W);
  y = drawCheckboxes(doc, ['Teacher', 'Parent/Guardian', 'Self-Referral', 'Administrator', 'Other'], MARGIN, y, 3);
  y += 2;
  y = drawField(doc, 'Referral Reason:', MARGIN, y, CONTENT_W);
  y = drawLines(doc, y, 3, MARGIN, CONTENT_W);

  y = drawSection(doc, 'Planned Response', y);
  y = drawField(doc, 'Planned Services:', MARGIN, y, CONTENT_W);
  y = drawLines(doc, y, 3, MARGIN, CONTENT_W);
  y = drawField(doc, 'Estimated Start Date:', MARGIN, y, 80);
  y += 5;

  y = checkPage(doc, y, 50);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...BLACK);
  const closing = doc.splitTextToSize(
    'Please do not hesitate to contact me if you have any questions or concerns. ' +
    'We look forward to working with your family to support your child\'s success.',
    CONTENT_W
  );
  doc.text(closing, MARGIN, y);
  y += closing.length * 5 + 10;

  doc.setFontSize(10);
  doc.setTextColor(...BLACK);
  doc.text('Sincerely,', MARGIN, y);
  y += 12;
  y = drawSignature(doc, 'School Counselor', y);

  drawFooter(doc);
  doc.save(`Referral-Acknowledgment-${student?.name?.replace(/\s+/g, '-') || 'Student'}-${shortDate()}.pdf`);
}

